#!/usr/bin/env node
// The pages outside the SPA (#1596, epic #1531 Phase 12) — the sign-in, TOTP, change-password and
// device-link templates the server renders — share the app's ONE palette and primitives instead of
// restating them as hex. This writes the app's own stylesheets into the server's public static
// folder (`src/agent_sessions/static/nightjar/`), served at `/static/nightjar/…` before sign-in:
//
//   tokens.css    web/src/tokens.css, plus its light block applied under
//                 `prefers-color-scheme: light` — these pages have no stored theme choice
//   fonts.css     web/src/theme/fonts.css with the font URLs pointing beside it
//   nightjar.css  web/src/components/hud/nightjar.css (the primitives), verbatim
//   motion.css    web/src/theme/motion.css (durations, keyframes, mode rules), verbatim
//   fonts/*.woff2 the self-hosted faces
//
// The output is committed (the server ships without a web build in some installs) and
// `src/theme/pageTokens.test.ts` regenerates it in memory and fails on any drift. Run it after
// changing any source: `node scripts/emit-page-tokens.mjs` (or `npm run build`, which runs it).
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = resolve(WEB, "../src/agent_sessions/static/nightjar");
const SRC = {
  tokens: join(WEB, "src/tokens.css"),
  fonts: join(WEB, "src/theme/fonts.css"),
  nightjar: join(WEB, "src/components/hud/nightjar.css"),
  motion: join(WEB, "src/theme/motion.css"),
  fontDir: join(WEB, "src/assets/fonts"),
};
const HEAD = (from) =>
  `/* GENERATED by web/scripts/emit-page-tokens.mjs from ${from} — do not edit; edit the source and\n` +
  ` * re-run the script (pinned by web/src/theme/pageTokens.test.ts). */\n`;

/** The light block's body, applied when the DEVICE prefers light and no theme attribute is set. */
function lightForDevice(tokens) {
  // The light block's selector may be a list (`:root[data-theme="light"], [data-theme-scope="light"]`
  // since #1574): match through to its opening brace.
  const m = /:root\[data-theme="light"\][^{]*\{([\s\S]*?)\n\}/.exec(tokens);
  if (!m) throw new Error('tokens.css has no :root[data-theme="light"] block');
  return (
    "\n/* The pages outside the SPA have no stored theme: they follow the device (#1596). */\n" +
    "@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {" +
    m[1].replace(/\n/g, "\n  ") +
    "\n  }\n}\n"
  );
}

/** The primitives' own light-theme rules (e.g. the atmosphere's daylight look), restated for a
 *  device that prefers light — top-level `:root[data-theme="light"] …` rules only (none sits in
 *  an at-rule today; one that did would be skipped, not mis-scoped). */
function lightRulesForDevice(css) {
  const rules = [];
  for (const m of css.matchAll(/(^|\n)((?![@\s])[^{}]*:root\[data-theme="light"\][^{}]*)\{([^{}]*)\}/g)) {
    const sel = m[2].trim().replace(/:root\[data-theme="light"\]/g, ":root:not([data-theme])");
    rules.push(`  ${sel.replace(/\n/g, "\n  ")} {${m[3].replace(/\n/g, "\n  ")}}`);
  }
  if (!rules.length) return "";
  return (
    "\n/* The pages outside the SPA follow the device (#1596): the light rules above, for it. */\n" +
    `@media (prefers-color-scheme: light) {\n${rules.join("\n")}\n}\n`
  );
}

/** Every generated file, as `name → contents` (strings) or `name → source path` (binary copies). */
export function pageFiles() {
  const tokens = readFileSync(SRC.tokens, "utf8");
  const fonts = readFileSync(SRC.fonts, "utf8").replace(/url\("\.\.\/assets\/fonts\//g, 'url("fonts/');
  const out = {
    "tokens.css": HEAD("web/src/tokens.css") + tokens + lightForDevice(tokens),
    "fonts.css": HEAD("web/src/theme/fonts.css") + fonts,
    "nightjar.css": (() => {
      const css = readFileSync(SRC.nightjar, "utf8");
      return HEAD("web/src/components/hud/nightjar.css") + css + lightRulesForDevice(css);
    })(),
    "motion.css": HEAD("web/src/theme/motion.css") + readFileSync(SRC.motion, "utf8"),
  };
  const binaries = {};
  for (const f of readdirSync(SRC.fontDir).filter((n) => n.endsWith(".woff2")))
    binaries[`fonts/${f}`] = join(SRC.fontDir, f);
  return { text: out, binaries };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { text, binaries } = pageFiles();
  mkdirSync(join(OUT, "fonts"), { recursive: true });
  for (const [name, body] of Object.entries(text)) writeFileSync(join(OUT, name), body);
  for (const [name, from] of Object.entries(binaries)) copyFileSync(from, join(OUT, name));
  console.log(`emit-page-tokens: ${Object.keys(text).length + Object.keys(binaries).length} files → ${OUT}`);
}
