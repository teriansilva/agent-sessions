SWAP = REPO / ".forgejo" / "scripts" / "landing-blog-swap.sh"


def _swap(*args):
    env = {"PATH": "/usr/bin:/bin", "SUDO": ""}
    return subprocess.run(
        ["bash", str(SWAP), *map(str, args)], capture_output=True, text=True, env=env
    )


def _tarball(tmp_path, name, marker, *, broken=False):
    src = tmp_path / f"src-{name}" / "blog"
    src.mkdir(parents=True)
    if not broken:
        (src / "index.html").write_text(marker)
    out = tmp_path / f"{name}.tgz"
    subprocess.run(["tar", "-C", str(src.parent), "-czf", str(out), "blog"], check=True)
    return out


def test_the_blog_deploy_switches_atomically_keeps_the_old_release_on_failure_and_rolls_back(
    tmp_path,
):
    docroot, releases = tmp_path / "www", tmp_path / "releases"
    docroot.mkdir()
    live = docroot / "blog" / "index.html"

    assert _swap("install", _tarball(tmp_path, "v1", "one"), docroot, releases).returncode == 0
    assert (docroot / "blog").is_symlink() and live.read_text() == "one"
    assert not str((docroot / "blog").resolve()).startswith(
        str(docroot)
    ), "releases live outside the web root"

    assert _swap("install", _tarball(tmp_path, "v2", "two"), docroot, releases).returncode == 0
    assert live.read_text() == "two"

    # A release that fails at any step (here: no blog/index.html) never goes live.
    bad = _swap("install", _tarball(tmp_path, "v3", "", broken=True), docroot, releases)
    assert bad.returncode != 0 and live.read_text() == "two"
    garbage = tmp_path / "garbage.tgz"
    garbage.write_bytes(b"not a tarball")
    assert _swap("install", garbage, docroot, releases).returncode != 0
    assert live.read_text() == "two"
    assert not (docroot / ".blog-next").exists()

    r = _swap("rollback", docroot, releases)
    assert r.returncode == 0, r.stderr
    assert live.read_text() == "one", "rollback restores the previous release"


def test_the_blog_deploy_keeps_four_releases_and_never_prunes_the_live_one(tmp_path):
    docroot, releases = tmp_path / "www", tmp_path / "releases"
