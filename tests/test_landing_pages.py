def test_an_inline_image_is_validated_and_shipped_like_a_lone_one(tmp_path):
    b = _builder()
    post = tmp_path / "a-post"
    post.mkdir()
    (post / "pic.webp").write_bytes(b"x")
    r = b.Renderer(post)
    html = r.render("Text ![a picture](pic.webp) text.\n")
    assert "pic.webp" in r.files_used, "an inline image is copied with the post"
    assert 'loading="lazy"' in html and r.count["images"] == 1
    with pytest.raises(b.BuildError, match="no alt text"):
        b.Renderer(post).render("Text ![](pic.webp) text.\n")
    with pytest.raises(b.BuildError, match="missing or unsafe media"):
        b.Renderer(post).render("Text ![a picture](nope.webp) text.\n")
    with pytest.raises(b.BuildError, match="missing or unsafe media"):
        b.Renderer(post).render("Text ![a picture](../pic.webp) text.\n")
    (post / "huge.webp").write_bytes(b"x" * (b.MAX_FILE + 1))
    with pytest.raises(b.BuildError, match="over the"):
        b.Renderer(post).render("Text ![a picture](huge.webp) text.\n")


