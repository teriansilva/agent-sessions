def test_the_feed_is_atom_with_an_author_for_every_entry():
    import xml.etree.ElementTree as ET

    atom = "{http://www.w3.org/2005/Atom}"
    root = ET.parse(LANDING / "blog" / "feed.xml").getroot()
    assert root.tag == f"{atom}feed"
    entries = root.findall(f"{atom}entry")
    assert entries
    feed_author = root.find(f"{atom}author/{atom}name")
    for e in entries:
        # RFC 4287 §4.1.1: an author on the feed, or on every entry. Both are written.
        assert e.find(f"{atom}author/{atom}name") is not None or feed_author is not None
        assert e.find(f"{atom}author/{atom}name").text.strip()
        for el in ("id", "title", "updated"):
            assert e.find(f"{atom}{el}") is not None, el
    assert feed_author is not None and feed_author.text == "BattleLab"


