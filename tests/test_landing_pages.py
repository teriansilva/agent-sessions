def test_the_faq_structured_data_matches_the_visible_faq():
    html = (LANDING / "index.html").read_text()
    visible = [
        re.sub(r"<[^>]+>", "", q)
        for q in re.findall(r'<div class="faq-g">.*?</div>', html, flags=re.S)
        for q in re.findall(r"<summary>(.*?)</summary>", q)
    ]
    graph = json.loads(
        re.search(
            r'<script type="application/ld\+json">\n(.*?)\n</script>', html, flags=re.S
        ).group(1)
    )
    faq = next(n for n in graph["@graph"] if n["@type"] == "FAQPage")
    import html as _h

    assert [q["name"] for q in faq["mainEntity"]] == [_h.unescape(v) for v in visible]
    assert len(visible) >= 15


def test_a_broken_post_fails_the_build(tmp_path):
    b = _builder()
    post = tmp_path / "a-post"
    post.mkdir()
    (post / "pic.webp").write_bytes(b"x")
